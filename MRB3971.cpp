static inline void gpio_set_mask(uint32_t mask0, uint32_t mask1) {
    if (mask0) REG_WRITE(GPIO_OUT_W1TS_REG, mask0);
    if (mask1) REG_WRITE(GPIO_OUT1_W1TS_REG, mask1);
}

static inline void gpio_clear_mask(uint32_t mask0, uint32_t mask1) {
    if (mask0) REG_WRITE(GPIO_OUT_W1TC_REG, mask0);
    if (mask1) REG_WRITE(GPIO_OUT1_W1TC_REG, mask1);
}

// ============================================================
//  Constructor
// ============================================================
MRB3971::MRB3971(uint8_t cs, uint8_t rs, uint8_t rd, uint8_t wr, int8_t rst,
                 const uint8_t *data_pins, uint8_t bus_width, uint8_t pin) {
    ets_printf("[MRB3971] CONSTRUCTOR cs=%d rs=%d rd=%d wr=%d rst=%d\n", cs, rs, rd, wr, rst);
    _cs = cs;   pinMode(_cs,  OUTPUT); digitalWrite(_cs,  HIGH);
    _rs = rs;   pinMode(_rs,  OUTPUT); digitalWrite(_rs,  HIGH);
    _rd = rd;   pinMode(_rd,  OUTPUT); digitalWrite(_rd,  HIGH);
    _wr = wr;   pinMode(_wr,  OUTPUT); digitalWrite(_wr,  HIGH);
    _rst = rst;
    if (_rst >= 0) {
        pinMode((uint8_t)_rst, OUTPUT);
        digitalWrite((uint8_t)_rst, HIGH);
    }
    ets_printf("[MRB3971] pins done, computing masks...\n");

    _csbit0  = (_cs  < 32) ? (1UL << _cs)       : 0;
    _csbit1  = (_cs  >= 32) ? (1UL << (_cs-32)) : 0;
    _rsbit0  = (_rs  < 32) ? (1UL << _rs)       : 0;
    _rsbit1  = (_rs  >= 32) ? (1UL << (_rs-32)) : 0;
    _rdbit0  = (_rd  < 32) ? (1UL << _rd)       : 0;
    _rdbit1  = (_rd  >= 32) ? (1UL << (_rd-32)) : 0;
    _wrbit0  = (_wr  < 32) ? (1UL << _wr)       : 0;
    _wrbit1  = (_wr  >= 32) ? (1UL << (_wr-32)) : 0;
    _rstbit0 = (_rst >= 0 && _rst < 32) ? (1UL << _rst)       : 0;
    _rstbit1 = (_rst >= 32)              ? (1UL << (_rst-32)) : 0;

#ifdef LCD_16BIT
    _bus_width = 16;
#else
    _bus_width = 8;
#endif
    if (bus_width < _bus_width) {
        _bus_width = bus_width;
    }

    memset(_data_pins, 0, sizeof(_data_pins));
    _data_mask0 = 0;
    _data_mask1 = 0;
    for (uint8_t i = 0; i < _bus_width; i++) {
        _data_pins[i] = data_pins[i];
        if (_data_pins[i] < 32) {
            _data_mask0 |= (1UL << _data_pins[i]);
        } else {
            _data_mask1 |= (1UL << (_data_pins[i] - 32));
        }
    }

    _parallel0 = _data_pins[0];
    _contiguous_bank = (_parallel0 < 32) ? 0 : 1;
    _is_contiguous = true;
    for (uint8_t i = 1; i < _bus_width; i++) {
        if (_data_pins[i] != (uint8_t)(_parallel0 + i) ||
            ((_data_pins[i] < 32) ? 0 : 1) != _contiguous_bank) {
            _is_contiguous = false;
            break;
        }
    }
    if (_is_contiguous) {
        uint32_t wmask = (_bus_width == 16) ? 0xFFFFUL : 0xFFUL;
        if (_contiguous_bank == 0) {
            _contiguous_mask = (wmask << _parallel0);
        } else {
            _contiguous_mask = (wmask << (_parallel0 - 32));
        }
    } else {
        _contiguous_mask = 0;
    }

    parallel_setup();
    _pin = pin; pinMode(_pin, OUTPUT);
    ets_printf("[MRB3971] CONSTRUCTOR done\n");
}

void MRB3971::ledon()  { digitalWrite(_pin, HIGH); }
void MRB3971::ledoff() { digitalWrite(_pin, LOW);  }

// ============================================================
//  Parallel bus (8-bit or 16-bit)
// ============================================================
void MRB3971::parallel_setup(void) {
    for (uint8_t i = 0; i < _bus_width; i++) {
        pinMode(_data_pins[i], INPUT);
    }
}
void MRB3971::set_inputs(void)  {
    if (_is_contiguous) {
        if (_contiguous_bank == 0) {
            REG_WRITE(GPIO_ENABLE_W1TC_REG, _contiguous_mask);
        } else {
            REG_WRITE(GPIO_ENABLE1_W1TC_REG, _contiguous_mask);
        }
    } else {
        if (_data_mask0) REG_WRITE(GPIO_ENABLE_W1TC_REG, _data_mask0);
        if (_data_mask1) REG_WRITE(GPIO_ENABLE1_W1TC_REG, _data_mask1);
    }
}
void MRB3971::set_outputs(void) {
    if (_is_contiguous) {
        if (_contiguous_bank == 0) {
            REG_WRITE(GPIO_ENABLE_W1TS_REG, _contiguous_mask);
        } else {
            REG_WRITE(GPIO_ENABLE1_W1TS_REG, _contiguous_mask);
        }
    } else {
        if (_data_mask0) REG_WRITE(GPIO_ENABLE_W1TS_REG, _data_mask0);
        if (_data_mask1) REG_WRITE(GPIO_ENABLE1_W1TS_REG, _data_mask1);
    }
}

uint16_t MRB3971::parallel_read(void) {
    if (_is_contiguous) {
        if (_contiguous_bank == 0) {
            uint32_t in = REG_READ(GPIO_IN_REG);
            if (_bus_width == 16) return (uint16_t)((in >> _parallel0) & 0xFFFFU);
            return (uint16_t)((in >> _parallel0) & 0xFFU);
        }
        uint32_t in1 = REG_READ(GPIO_IN1_REG);
        uint8_t s = _parallel0 - 32;
        if (_bus_width == 16) return (uint16_t)((in1 >> s) & 0xFFFFU);
        return (uint16_t)((in1 >> s) & 0xFFU);
    }

    uint16_t value = 0;
    uint32_t in0 = REG_READ(GPIO_IN_REG);
    uint32_t in1 = REG_READ(GPIO_IN1_REG);
    for (uint8_t i = 0; i < _bus_width; i++) {
        uint8_t p = _data_pins[i];
        bool bit_set = (p < 32) ? (in0 & (1UL << p)) : (in1 & (1UL << (p - 32)));
        if (bit_set) {
            value |= (1U << i);
        }
    }
    return value;
}
void MRB3971::parallel_write(uint16_t value) {
    if (_is_contiguous) {
        if (_contiguous_bank == 0) {
            uint32_t out = REG_READ(GPIO_OUT_REG) & ~_contiguous_mask;
            out |= ((uint32_t)value << _parallel0) & _contiguous_mask;
            REG_WRITE(GPIO_OUT_REG, out);
        } else {
            uint32_t s = _parallel0 - 32;
            uint32_t out1 = REG_READ(GPIO_OUT1_REG) & ~_contiguous_mask;
            out1 |= ((uint32_t)value << s) & _contiguous_mask;
            REG_WRITE(GPIO_OUT1_REG, out1);
        }
        return;
    }

    uint32_t set_mask0 = 0;
    uint32_t clear_mask0 = 0;
    uint32_t set_mask1 = 0;
    uint32_t clear_mask1 = 0;
    for (uint8_t i = 0; i < _bus_width; i++) {
        uint8_t p = _data_pins[i];
        if (p < 32) {
            uint32_t bit = (1UL << p);
            if (value & (1U << i)) {
                set_mask0 |= bit;
            } else {
                clear_mask0 |= bit;
            }
        } else {
            uint32_t bit = (1UL << (p - 32));
            if (value & (1U << i)) {
                set_mask1 |= bit;
            } else {
                clear_mask1 |= bit;
            }
        }
    }
    if (clear_mask0) REG_WRITE(GPIO_OUT_W1TC_REG, clear_mask0);
    if (set_mask0) REG_WRITE(GPIO_OUT_W1TS_REG, set_mask0);
    if (clear_mask1) REG_WRITE(GPIO_OUT1_W1TC_REG, clear_mask1);
    if (set_mask1) REG_WRITE(GPIO_OUT1_W1TS_REG, set_mask1);
}

void MRB3971::writex2(uint8_t HVAL, uint8_t LVAL) {
    set_outputs();
    gpio_clear_mask(_csbit0, _csbit1);
#ifdef LCD_16BIT
    parallel_write((uint16_t)((HVAL << 8) | LVAL));
    gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
#else
    parallel_write(HVAL);
    gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
    parallel_write(LVAL);
    gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
#endif
    gpio_set_mask(_csbit0, _csbit1);
}

void MRB3971::WR_REG(uint16_t Reg) {
    gpio_clear_mask(_rsbit0, _rsbit1);
    writex2((Reg >> 8) & 0xFF, Reg & 0xFF);
}
void MRB3971::WR_DATA(uint16_t Data) {
    gpio_set_mask(_rsbit0, _rsbit1);
    writex2((Data >> 8) & 0xFF, Data & 0xFF);
}
void MRB3971::WriteReg(uint16_t LCD_Reg, uint16_t LCD_RegValue) {
    WR_REG(LCD_Reg); WR_DATA(LCD_RegValue);
}

uint16_t MRB3971::RD_DATA(void) {
    uint16_t rd;
    gpio_set_mask(_rsbit0, _rsbit1);
    set_inputs();
    gpio_clear_mask(_csbit0, _csbit1);
    gpio_clear_mask(_rdbit0, _rdbit1);
    delayMicroseconds(1);
    rd = parallel_read();
    gpio_set_mask(_rdbit0, _rdbit1);
    gpio_set_mask(_csbit0, _csbit1);
    return rd;
}
void MRB3971::ReadReg(uint16_t LCD_Reg, uint16_t *Rval, int n) {
    WR_REG(LCD_Reg);
    while (n--) {
#ifdef LCD_8BIT
        *(Rval++) = (RD_DATA() << 8) | RD_DATA();
#else
        *(Rval++) = RD_DATA();
#endif
    }
}

void MRB3971::WriteRAM_Prepare(void) { WR_REG(lcddev.wramcmd); }

void MRB3971::FillWindow(uint16_t Color) {
    FillPixels(Color, (uint32_t)lcddev.w * lcddev.h);
}

void MRB3971::FillPixels(uint16_t Color, uint32_t count) {
    uint8_t colh = (Color >> 8) & 0xFF;
    uint8_t coll =  Color       & 0xFF;
    set_outputs();
    gpio_clear_mask(_csbit0, _csbit1);
    gpio_set_mask(_rsbit0, _rsbit1);
    for (uint32_t i = 0; i < count; i++) {
#ifdef LCD_8BIT
        parallel_write(colh);
        gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
        parallel_write(coll);
        gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
#else
        parallel_write(Color);
        gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
#endif
    }
    gpio_set_mask(_csbit0, _csbit1);
}

void MRB3971::Reset(void) {
    if (_rst < 0) return;  // RST not connected (hardware pull-up)
    delay(50); digitalWrite((uint8_t)_rst, LOW);
    delay(50); digitalWrite((uint8_t)_rst, HIGH);
    delay(50);
}

void MRB3971::SetWindow(uint16_t xStar, uint16_t yStar, uint16_t xEnd, uint16_t yEnd) {
    WriteReg(lcddev.setxcmd,     xStar >> 8);
    WriteReg(lcddev.setxcmd + 1, xStar & 0xFF);
    WriteReg(lcddev.setxcmd + 2, xEnd  >> 8);
    WriteReg(lcddev.setxcmd + 3, xEnd  & 0xFF);
    WriteReg(lcddev.setycmd,     yStar >> 8);
    WriteReg(lcddev.setycmd + 1, yStar & 0xFF);
    WriteReg(lcddev.setycmd + 2, yEnd  >> 8);
    WriteReg(lcddev.setycmd + 3, yEnd  & 0xFF);
    WriteRAM_Prepare();
}

void MRB3971::direction(uint8_t dir) {
    lcddev.setxcmd = 0x2A00; lcddev.setycmd = 0x2B00;
    lcddev.wramcmd = 0x2C00; lcddev.rramcmd = 0x2E00;
    switch (dir) {
        case 0: lcddev.w=LCD_W; lcddev.h=LCD_H; WriteReg(0x3600,0x00);          break;
        case 1: lcddev.w=LCD_H; lcddev.h=LCD_W; WriteReg(0x3600,(1<<5)|(1<<6)); break;
        case 2: lcddev.w=LCD_W; lcddev.h=LCD_H; WriteReg(0x3600,(1<<7)|(1<<6)); break;
        case 3: lcddev.w=LCD_H; lcddev.h=LCD_W; WriteReg(0x3600,(1<<7)|(1<<5)); break;
        default: break;
    }
}

uint16_t MRB3971::Read_ID(void) {
    uint16_t val, valt;
    uint8_t iniID[] = {0x55,0xAA,0x52,0x08,0x01};
    WriteRegM(0xF000, sizeof(iniID), iniID);
    ReadReg(0x0c00, &valt, 1); ReadReg(0x0d00, &val, 1);
    val |= (valt <<= 8);
    return val;
}
void MRB3971::WriteRegM(uint16_t adr, uint16_t len, uint8_t dat[]) {
    for (int i = 0; i < len; i++) WriteReg(adr++, dat[i]);
}

