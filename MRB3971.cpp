void MRB3971::DrawCircle(uint16_t x0, uint16_t y0, uint8_t r) {
    int a=0,b=r,di=3-(r<<1);
    while (a<=b) {
        DrawPoint(x0-b,y0-a); DrawPoint(x0+b,y0-a); DrawPoint(x0-a,y0+b);
        DrawPoint(x0-b,y0+a); DrawPoint(x0-a,y0-b); DrawPoint(x0+b,y0+a);
        DrawPoint(x0+a,y0-b); DrawPoint(x0+a,y0+b); DrawPoint(x0-b,y0+a);
        a++;
        if (di<0) di+=4*a+6; else { di+=10+4*(a-b); b--; }
        DrawPoint(x0+a,y0+b);
    }
}
void MRB3971::DrawLine(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2) {
    int xerr=0,yerr=0,delta_x=x2-x1,delta_y=y2-y1,distance,incx,incy;
    uint16_t uRow=x1,uCol=y1;
    if(delta_x>0) incx=1; else if(delta_x==0) incx=0; else{incx=-1;delta_x=-delta_x;}
    if(delta_y>0) incy=1; else if(delta_y==0) incy=0; else{incy=-1;delta_y=-delta_y;}
    distance=(delta_x>delta_y)?delta_x:delta_y;
    for(int t=0;t<=distance+1;t++){
        DrawPoint(uRow,uCol); xerr+=delta_x; yerr+=delta_y;
        if(xerr>distance){xerr-=distance;uRow+=incx;}
        if(yerr>distance){yerr-=distance;uCol+=incy;}
    }
}
void MRB3971::DrawRectangle(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2) {
    DrawLine(x1,y1,x2,y1); DrawLine(x1,y1,x1,y2);
    DrawLine(x1,y2,x2,y2); DrawLine(x2,y1,x2,y2);
}

// ============================================================
//  Paint flood fill
// ============================================================
#define MAXSIZE 256
#define MINX 0
#define MINY 0
#define MAXX 800
#define MAXY 480

struct BufStr { uint16_t sx; uint16_t sy; };
static struct BufStr buff[MAXSIZE];
static struct BufStr *sIdx, *eIdx;

void MRB3971::pset(uint16_t x, uint16_t y, uint16_t col) { POINT_COLOR=col; DrawPoint(x,y); }
uint16_t MRB3971::point(uint16_t x, uint16_t y) { return ReadPoint(x,y); }

void MRB3971::scanLine(uint16_t lx, uint16_t rx, uint16_t y, uint16_t col) {
    while (lx<=rx) {
        for(;lx<=rx;lx++) if(point(lx,y)==col) break;
        if(point(lx,y)!=col) break;
        for(;lx<=rx;lx++) if(point(lx,y)!=col) break;
        eIdx->sx=lx-1; eIdx->sy=y;
        if(++eIdx==&buff[MAXSIZE]) eIdx=buff;
    }
}
void MRB3971::paint(uint16_t x, uint16_t y, uint16_t paintCol) {
    uint16_t lx,rx,ly,i;
    uint16_t col=point(x,y);
    if(col==paintCol) return;
    sIdx=buff; eIdx=buff+1; sIdx->sx=x; sIdx->sy=y;
    do {
        lx=rx=sIdx->sx; ly=sIdx->sy;
        if(++sIdx==&buff[MAXSIZE]) sIdx=buff;
        if(point(lx,ly)!=col) continue;
        while(rx<MAXX){ if(point(rx+1,ly)!=col) break; rx++; }
        while(lx>MINX){ if(point(lx-1,ly)!=col) break; lx--; }
        for(i=lx;i<=rx;i++) pset(i,ly,paintCol);
        if(ly-1>=MINY) scanLine(lx,rx,ly-1,col);
        if(ly+1<=MAXY) scanLine(lx,rx,ly+1,col);
    } while(sIdx!=eIdx);
}

// ============================================================
//  FlushBuffer — bulk RGB565 write for LVGL flush callback
// ============================================================
void MRB3971::FlushBuffer(const uint16_t *buf, uint32_t len) {
    gpio_set_mask(_rsbit0, _rsbit1);  // RS high = data mode
    set_outputs();
    gpio_clear_mask(_csbit0, _csbit1);  // CS low — keep low for whole transfer
    while (len--) {
        uint16_t c = *buf++;
#ifdef LCD_16BIT
        parallel_write(c);
        gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
#else
        parallel_write((uint8_t)(c >> 8));
        gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
        parallel_write((uint8_t)(c & 0xFF));
        gpio_clear_mask(_wrbit0, _wrbit1); gpio_set_mask(_wrbit0, _wrbit1);
#endif
    }
    gpio_set_mask(_csbit0, _csbit1);  // CS high
}
