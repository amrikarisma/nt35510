void MRB3971::DrawPoint(uint16_t x, uint16_t y) {
    if (x < lcddev.w && y < lcddev.h) { SetWindow(x,y,x,y); WR_DATA(POINT_COLOR); }
}
uint16_t MRB3971::ReadPoint(uint16_t x, uint16_t y) {
    uint16_t d,r,g,b;
    if (x >= lcddev.w || y >= lcddev.h) return 0;
    SetWindow(x,y,x,y); WR_REG(lcddev.rramcmd);
    set_inputs();
    gpio_set_mask(_rsbit0, _rsbit1); gpio_clear_mask(_csbit0, _csbit1);
    gpio_clear_mask(_rdbit0, _rdbit1); delayMicroseconds(1); d=parallel_read(); gpio_set_mask(_rdbit0, _rdbit1);
    gpio_clear_mask(_rdbit0, _rdbit1); delayMicroseconds(1); r=parallel_read(); gpio_set_mask(_rdbit0, _rdbit1);
    gpio_clear_mask(_rdbit0, _rdbit1); delayMicroseconds(1); g=parallel_read(); gpio_set_mask(_rdbit0, _rdbit1);
    gpio_clear_mask(_rdbit0, _rdbit1); delayMicroseconds(1); b=parallel_read(); gpio_set_mask(_rdbit0, _rdbit1);
    gpio_set_mask(_csbit0, _csbit1);
    return ((r&0xF8)<<8)|((g&0xFC)<<3)|((b&0xF8)>>3);
}
void MRB3971::ShowChar(uint16_t x, uint16_t y, uint8_t num, uint8_t mode) {
    uint8_t temp,pos,t; uint16_t x0=x, colortemp=POINT_COLOR;
    if (x>=lcddev.w || y>=lcddev.h) return;
    num = num - ' '; SetWindow(x,y,x+7,y+15);
    if (!mode) {
        for (pos=0;pos<16;pos++) {
            temp=pgm_read_byte(asc2_1608+(uint16_t)num*16+pos);
            for (t=0;t<8;t++) { POINT_COLOR=(temp&0x01)?colortemp:BACK_COLOR; WR_DATA(POINT_COLOR); temp>>=1; x++; }
            x=x0; y++;
        }
    } else {
        for (pos=0;pos<16;pos++) {
            temp=pgm_read_byte(asc2_1608+(uint16_t)num*16+pos);
            for (t=0;t<8;t++) { if(temp&0x01) DrawPoint(x+t,y+pos); temp>>=1; }
        }
    }
    POINT_COLOR=colortemp;
}
void MRB3971::ShowString(uint16_t x, uint16_t y, uint8_t *p) {
    while (*p!='\0') {
        if (x>lcddev.w-8)  { x=0; y+=16; }
        if (y>lcddev.h-16) { y=x=0; }
        ShowChar(x,y,*p,0); x+=8; p++;
    }
}
